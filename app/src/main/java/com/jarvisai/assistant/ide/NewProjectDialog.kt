/**
 * Phase 4: Project Scaffolder & Starter Template Generator (`NewProjectDialog`).
 * Supports Python, Node.js, Web App (HTML/CSS/JS), C++, and Blank workspaces,
 * automatically generating boilerplate code and `.ide/launch.json`.
 */
enum class IdeProjectTemplate(
    val id: String,
    val title: String,
    val description: String,
    val primaryEntryFile: String
) {
    PYTHON("python", "Python 3 Script", "main.py + .ide/launch.json", "main.py"),
    NODE("node", "Node.js Application", "index.js + package.json + .ide/launch.json", "index.js"),
    WEB("web", "Web App (HTML/CSS/JS)", "index.html + style.css + app.js + live preview", "index.html"),
    CPP("cpp", "C++17 Native Binary", "main.cpp + g++ build & run config", "main.cpp"),
    BLANK("blank", "Blank Workspace", "README.md + empty directory", "README.md")
}

object ProjectScaffoldEngine {

    fun createProject(
        parentDirectory: File,
        projectName: String,
        template: IdeProjectTemplate
    ): Result<File> = runCatching {
        val sanitizedName = projectName.trim().replace(Regex("[^a-zA-Z0-9._-]"), "_").ifBlank { "new_project" }
        val projectDir = File(parentDirectory, sanitizedName).apply { if (!exists()) mkdirs() }

        when (template) {
            IdeProjectTemplate.PYTHON -> {
                File(projectDir, "main.py").writeText(
                    """
                    #!/usr/bin/env python3
                    import sys
                    import platform

                    def main():
                        print(f"🚀 Running { '$sanitizedName' } on Python {sys.version.split()[0]} ({platform.machine()})")

                    if __name__ == "__main__":
                        main()
                    """.trimIndent() + "\n"
                )
                RunConfigManager.saveConfigurations(
                    projectPath = projectDir.absolutePath,
                    configs = listOf(
                        RunConfiguration(
                            name = "Run main.py (Python 3)",
                            type = "terminal",
                            command = "python3 main.py",
                            file = "main.py",
                            cwd = projectDir.absolutePath,
                            isDefault = true
                        )
                    )
                )
            }

            IdeProjectTemplate.NODE -> {
                File(projectDir, "package.json").writeText(
                    """
                    {
                      "name": "${sanitizedName.lowercase()}",
                      "version": "1.0.0",
                      "description": "Generated by Jarvis Mobile IDE",
                      "main": "index.js",
                      "scripts": {
                        "start": "node index.js"
                      }
                    }
                    """.trimIndent() + "\n"
                )
                File(projectDir, "index.js").writeText(
                    """
                    const os = require('os');

                    console.log('⚡ Node.js project "$sanitizedName" initialized!');
                    console.log('Platform:', os.platform(), os.arch(), 'Node:', process.version);
                    """.trimIndent() + "\n"
                )
                RunConfigManager.saveConfigurations(
                    projectPath = projectDir.absolutePath,
                    configs = listOf(
                        RunConfiguration(
                            name = "npm start (Node.js)",
                            type = "terminal",
                            command = "npm start",
                            file = "index.js",
                            cwd = projectDir.absolutePath,
                            isDefault = true
                        )
                    )
                )
            }

            IdeProjectTemplate.WEB -> {
                File(projectDir, "index.html").writeText(
                    """
                    <!DOCTYPE html>
                    <html lang="en">
                    <head>
                      <meta charset="UTF-8" />
                      <meta name="viewport" content="width=device-width, initial-scale=1.0" />
                      <title>$sanitizedName</title>
                      <link rel="stylesheet" href="style.css" />
                    </head>
                    <body>
                      <main class="card">
                        <h1>$sanitizedName</h1>
                        <p id="status">Interactive Web App Ready</p>
                        <button id="actionBtn">Run Action</button>
                      </main>
                      <script src="app.js"></script>
                    </body>
                    </html>
                    """.trimIndent() + "\n"
                )
                File(projectDir, "style.css").writeText(
                    """
                    body {
                      margin: 0;
                      min-height: 100vh;
                      display: flex;
                      align-items: center;
                      justify-content: center;
                      background: #0A0F1D;
                      color: #F0F6FC;
                      font-family: system-ui, sans-serif;
                    }
                    .card {
                      background: #111C35;
                      padding: 24px;
                      border-radius: 16px;
                      border: 1px solid #38BDF8;
                      text-align: center;
                    }
                    button {
                      background: #00E5FF;
                      color: #070B14;
                      border: none;
                      padding: 10px 20px;
                      border-radius: 8px;
                      font-weight: 700;
                      cursor: pointer;
                    }
                    """.trimIndent() + "\n"
                )
                File(projectDir, "app.js").writeText(
                    """
                    document.getElementById('actionBtn')?.addEventListener('click', () => {
                      const el = document.getElementById('status');
                      if (el) el.textContent = 'Clicked at ' + new Date().toLocaleTimeString();
                    });
                    """.trimIndent() + "\n"
                )
                RunConfigManager.saveConfigurations(
                    projectPath = projectDir.absolutePath,
                    configs = listOf(
                        RunConfiguration(
                            name = "Live Web Preview",
                            type = "webview",
                            command = "python3 -m http.server 4321",
                            file = "index.html",
                            cwd = projectDir.absolutePath,
                            isDefault = true
                        )
                    )
                )
            }

            IdeProjectTemplate.CPP -> {
                File(projectDir, "main.cpp").writeText(
                    """
                    #include <iostream>
                    #include <vector>
                    #include <string>

                    int main() {
                        std::cout << "⚡ C++17 Project [$sanitizedName] compiled and running!" << std::endl;
                        return 0;
                    }
                    """.trimIndent() + "\n"
                )
                RunConfigManager.saveConfigurations(
                    projectPath = projectDir.absolutePath,
                    configs = listOf(
                        RunConfiguration(
                            name = "Build & Run C++17 (g++)",
                            type = "terminal",
                            command = "g++ -O2 -std=c++17 main.cpp -o app_bin && ./app_bin",
                            file = "main.cpp",
                            cwd = projectDir.absolutePath,
                            isDefault = true
                        )
                    )
                )
            }

            IdeProjectTemplate.BLANK -> {
                File(projectDir, "README.md").writeText(
                    """
                    # $sanitizedName

                    Created with Jarvis Mobile IDE.
                    """.trimIndent() + "\n"
                )
            }
        }

        File(projectDir, template.primaryEntryFile)
    }
}

@Composable
fun NewProjectDialog(
    workspaceRoot: File,
    onProjectCreated: (projectDir: File, entryFile: File) -> Unit,
    onDismiss: () -> Unit
) {
    val effectiveParentDir = remember(workspaceRoot.absolutePath) {
        if (workspaceRoot.name == "home") File(workspaceRoot, "projects") else workspaceRoot
    }
    val scope = rememberCoroutineScope()
    var projectName by remember { mutableStateOf("my-app") }
    var selectedTemplate by remember { mutableStateOf(IdeProjectTemplate.PYTHON) }
    var errorMessage by remember { mutableStateOf<String?>(null) }
    var isCreating by remember { mutableStateOf(false) }

    Dialog(onDismissRequest = onDismiss) {
        Surface(
            modifier = Modifier
                .fillMaxWidth()
                .testTag("new_project_dialog"),
            color = Color(0xFF111C35),
            shape = RoundedCornerShape(18.dp)
        ) {
            Column(
                modifier = Modifier
                    .fillMaxWidth()
                    .verticalScroll(androidx.compose.foundation.rememberScrollState())
                    .padding(20.dp)
            ) {
                Text(
                    text = "Create New Project",
                    color = Color(0xFFF0F6FC),
                    fontSize = 18.sp,
                    fontWeight = FontWeight.Bold
                )
                Spacer(modifier = Modifier.height(4.dp))
                Text(
                    text = "Location: ${effectiveParentDir.absolutePath}",
                    color = Color(0xFF94A3B8),
                    fontSize = 11.sp
                )

                Spacer(modifier = Modifier.height(12.dp))

                OutlinedTextField(
                    value = projectName,
                    onValueChange = {
                        projectName = it
                        errorMessage = null
                    },
                    label = { Text("Project Folder Name") },
                    singleLine = true,
                    colors = androidx.compose.material3.OutlinedTextFieldDefaults.colors(
                        focusedTextColor = Color.White,
                        unfocusedTextColor = Color.White,
                        focusedLabelColor = Color(0xFF00E5FF),
                        unfocusedLabelColor = Color(0xFF94A3B8),
                        focusedBorderColor = Color(0xFF00E5FF),
                        unfocusedBorderColor = Color(0xFF334155),
                        cursorColor = Color(0xFF00E5FF)
                    ),
                    modifier = Modifier
                        .fillMaxWidth()
                        .testTag("new_project_name_input")
                )

                Spacer(modifier = Modifier.height(12.dp))

                Text(
                    text = "STARTER TEMPLATE",
                    color = Color(0xFF38BDF8),
                    fontSize = 11.sp,
                    fontWeight = FontWeight.Bold
                )

                Spacer(modifier = Modifier.height(8.dp))

                Column(verticalArrangement = Arrangement.spacedBy(8.dp)) {
                    IdeProjectTemplate.entries.forEach { tmpl ->
                        val isSelected = selectedTemplate == tmpl
                        Row(
                            modifier = Modifier
                                .fillMaxWidth()
                                .clip(RoundedCornerShape(10.dp))
                                .background(if (isSelected) Color(0xFF1E3A8A).copy(alpha = 0.45f) else Color(0xFF0A0F1D))
                                .border(
                                    width = 1.dp,
                                    color = if (isSelected) Color(0xFF00E5FF) else Color(0xFF1E293B),
                                    shape = RoundedCornerShape(10.dp)
                                )
                                .clickable { selectedTemplate = tmpl }
                                .padding(horizontal = 12.dp, vertical = 10.dp)
                                .testTag("project_template_${tmpl.id}"),
                            verticalAlignment = Alignment.CenterVertically,
                            horizontalArrangement = Arrangement.SpaceBetween
                        ) {
                            Column {
                                Text(
                                    text = tmpl.title,
                                    color = Color(0xFFF0F6FC),
                                    fontSize = 13.sp,
                                    fontWeight = FontWeight.SemiBold
                                )
                                Text(
                                    text = tmpl.description,
                                    color = Color(0xFF94A3B8),
                                    fontSize = 11.sp
                                )
                            }
                        }
                    }
                }

                if (errorMessage != null) {
                    Spacer(modifier = Modifier.height(8.dp))
                    Text(
                        text = errorMessage ?: "",
                        color = Color(0xFFF85149),
                        fontSize = 12.sp
                    )
                }

                Spacer(modifier = Modifier.height(16.dp))

                Row(
                    modifier = Modifier.fillMaxWidth(),
                    horizontalArrangement = Arrangement.spacedBy(10.dp)
                ) {
                    OutlinedButton(
                        onClick = onDismiss,
                        modifier = Modifier.weight(1f)
                    ) {
                        Text("Cancel", color = Color(0xFF94A3B8))
                    }
                    Button(
                        onClick = {
                            if (isCreating) return@Button
                            isCreating = true
                            scope.launch {
                                val res = kotlinx.coroutines.withContext(kotlinx.coroutines.Dispatchers.IO) {
                                    ProjectScaffoldEngine.createProject(
                                        parentDirectory = effectiveParentDir,
                                        projectName = projectName,
                                        template = selectedTemplate
                                    )
                                }
                                isCreating = false
                                res.onSuccess { entryFile ->
                                    onProjectCreated(entryFile.parentFile ?: effectiveParentDir, entryFile)
                                }.onFailure { err ->
                                    errorMessage = err.localizedMessage ?: "Failed to create project"
                                }
                            }
                        },
                        enabled = projectName.isNotBlank() && !isCreating,
                        colors = ButtonDefaults.buttonColors(containerColor = Color(0xFF00E5FF)),
                        modifier = Modifier
                            .weight(1f)
                            .testTag("create_project_confirm_button")
                    ) {
                        Text(
                            text = if (isCreating) "Creating..." else "Create Project",
                            color = Color(0xFF070B14),
                            fontWeight = FontWeight.Bold
                        )
                    }
                }
            }
        }
    }
}
