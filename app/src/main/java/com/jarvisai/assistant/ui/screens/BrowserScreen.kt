@SuppressLint("SetJavaScriptEnabled")
@Composable
fun BrowserScreen(
    initialUrl: String = "https://www.google.com",
    onBack: () -> Unit,
    onSummarizeContent: suspend (String) -> String = { "Page summary generated by JARVIS Neural Core." }
) {
    val context = LocalContext.current
    val coroutineScope = rememberCoroutineScope()
    val clipboardManager = LocalClipboardManager.current

    var currentUrl by remember { mutableStateOf(initialUrl) }
    var inputUrl by remember { mutableStateOf(initialUrl) }
    var currentTitle by remember { mutableStateOf("JARVIS Secure Web Portal") }
    var webViewRef by remember { mutableStateOf<WebView?>(null) }
    var isLoading by remember { mutableStateOf(false) }
    var canGoBack by remember { mutableStateOf(false) }
    var canGoForward by remember { mutableStateOf(false) }

    // AI Summary Dialog State
    var isSummarizing by remember { mutableStateOf(false) }
    var summaryResult by remember { mutableStateOf<String?>(null) }
    var isSummaryModalOpen by remember { mutableStateOf(false) }

    val quickBookmarks = listOf(
        "Google" to "https://www.google.com",
        "Wikipedia" to "https://en.wikipedia.org",
        "GitHub" to "https://github.com",
        "Gemini" to "https://gemini.google.com",
        "HackerNews" to "https://news.ycombinator.com",
        "TechCrunch" to "https://techcrunch.com"
    )

    fun navigateToUrl(target: String) {
        val trimmed = target.trim()
        val finalUrl = when {
            trimmed.startsWith("http://") || trimmed.startsWith("https://") -> trimmed
            trimmed.contains(".") && !trimmed.contains(" ") -> "https://$trimmed"
            else -> "https://www.google.com/search?q=" + Uri.encode(trimmed)
        }
        currentUrl = finalUrl
        inputUrl = finalUrl
        webViewRef?.loadUrl(finalUrl)
    }

    BackHandler {
        if (webViewRef?.canGoBack() == true) {
            webViewRef?.goBack()
        } else {
            onBack()
        }
    }

    Box(
        modifier = Modifier
            .fillMaxSize()
            .background(Color(0xFF070E1A))
    ) {
        Column(modifier = Modifier.fillMaxSize()) {
            // 1. TOP CYBER CONTROLS & URL BAR
            Column(
                modifier = Modifier
                    .fillMaxWidth()
                    .background(
                        Brush.verticalGradient(
                            colors = listOf(
                                Color(0xFF0F1A2E),
                                Color(0xFF0A1120)
                            )
                        )
                    )
                    .border(
                        width = 1.dp,
                        color = JarvisNeonCyan.copy(alpha = 0.25f),
                        shape = RoundedCornerShape(bottomStart = 20.dp, bottomEnd = 20.dp)
                    )
                    .padding(horizontal = 10.dp, vertical = 8.dp)
            ) {
                // Top Action Row
                Row(
                    modifier = Modifier.fillMaxWidth(),
                    verticalAlignment = Alignment.CenterVertically,
                    horizontalArrangement = Arrangement.SpaceBetween
                ) {
                    Row(
                        verticalAlignment = Alignment.CenterVertically,
                        horizontalArrangement = Arrangement.spacedBy(4.dp)
                    ) {
                        IconButton(
                            onClick = {
                                if (webViewRef?.canGoBack() == true) {
                                    webViewRef?.goBack()
                                } else {
                                    onBack()
                                }
                            },
                            modifier = Modifier.testTag("browser_back_btn")
                        ) {
                            Icon(
                                imageVector = Icons.AutoMirrored.Filled.ArrowBack,
                                contentDescription = "Back",
                                tint = if (canGoBack) JarvisNeonCyan else Color.White.copy(alpha = 0.5f)
                            )
                        }

                        IconButton(
                            onClick = {
                                webViewRef?.loadUrl("https://www.google.com")
                                inputUrl = "https://www.google.com"
                            },
                            modifier = Modifier.testTag("browser_home_btn")
                        ) {
                            Icon(
                                imageVector = Icons.Default.Home,
                                contentDescription = "Home",
                                tint = JarvisNeonCyan
                            )
                        }

                        IconButton(
                            onClick = { webViewRef?.reload() },
                            modifier = Modifier.testTag("browser_refresh_btn")
                        ) {
                            Icon(
                                imageVector = Icons.Default.Refresh,
                                contentDescription = "Reload",
                                tint = Color(0xFF80D8FF)
                            )
                        }
                    }

                    // Page Title Pill
                    Box(
                        modifier = Modifier
                            .weight(1f)
                            .padding(horizontal = 6.dp)
                            .clip(RoundedCornerShape(999.dp))
                            .background(Color(0xFF131D33))
                            .border(1.dp, Color.White.copy(alpha = 0.12f), RoundedCornerShape(999.dp))
                            .padding(horizontal = 10.dp, vertical = 4.dp),
                        contentAlignment = Alignment.Center
                    ) {
                        Text(
                            text = currentTitle,
                            style = MaterialTheme.typography.labelSmall,
                            color = Color.White,
                            fontWeight = FontWeight.Bold,
                            maxLines = 1,
                            overflow = TextOverflow.Ellipsis
                        )
                    }

                    // External Browser Button
                    IconButton(
                        onClick = {
                            try {
                                val browserIntent = Intent(Intent.ACTION_VIEW, Uri.parse(currentUrl))
                                context.startActivity(browserIntent)
                            } catch (_: Exception) {
                            }
                        },
                        modifier = Modifier.testTag("browser_open_external_btn")
                    ) {
                        Icon(
                            imageVector = Icons.AutoMirrored.Filled.OpenInNew,
                            contentDescription = "Open in Chrome",
                            tint = JarvisNeonCyan
                        )
                    }
                }

                Spacer(modifier = Modifier.height(6.dp))

                // Editable URL / Search Field
                OutlinedTextField(
                    value = inputUrl,
                    onValueChange = { inputUrl = it },
                    modifier = Modifier
                        .fillMaxWidth()
                        .height(52.dp)
                        .testTag("browser_url_input"),
                    placeholder = {
                        Text(
                            text = "Search or type web URL...",
                            fontSize = 12.sp,
                            color = JarvisTextMuted
                        )
                    },
                    leadingIcon = {
                        Icon(
                            imageVector = Icons.Default.Search,
                            contentDescription = null,
                            tint = JarvisNeonCyan,
                            modifier = Modifier.size(18.dp)
                        )
                    },
                    trailingIcon = {
                        Row(verticalAlignment = Alignment.CenterVertically) {
                            if (inputUrl.isNotBlank()) {
                                IconButton(
                                    onClick = { inputUrl = "" },
                                    modifier = Modifier.size(32.dp)
                                ) {
                                    Icon(
                                        imageVector = Icons.Default.Clear,
                                        contentDescription = "Clear",
                                        tint = JarvisTextSecondary,
                                        modifier = Modifier.size(16.dp)
                                    )
                                }
                            }
                            Box(
                                modifier = Modifier
                                    .padding(end = 4.dp)
                                    .clip(RoundedCornerShape(12.dp))
                                    .background(
                                        Brush.horizontalGradient(
                                            listOf(JarvisNeonCyan, JarvisNeonGreen)
                                        )
                                    )
                                    .clickable { navigateToUrl(inputUrl) }
                                    .padding(horizontal = 10.dp, vertical = 6.dp)
                                    .testTag("browser_go_btn")
                            ) {
                                Text(
                                    text = "GO",
                                    fontSize = 11.sp,
                                    fontWeight = FontWeight.ExtraBold,
                                    color = Color(0xFF050E18)
                                )
                            }
                        }
                    },
                    singleLine = true,
                    textStyle = MaterialTheme.typography.bodySmall.copy(
                        color = Color.White,
                        fontFamily = FontFamily.Monospace,
                        fontSize = 12.sp
                    ),
                    keyboardOptions = KeyboardOptions(imeAction = ImeAction.Go),
                    keyboardActions = KeyboardActions(onGo = { navigateToUrl(inputUrl) }),
                    shape = RoundedCornerShape(16.dp),
                    colors = OutlinedTextFieldDefaults.colors(
                        focusedBorderColor = JarvisNeonCyan,
                        unfocusedBorderColor = Color.White.copy(alpha = 0.20f),
                        focusedContainerColor = Color(0xFF0B1424),
                        unfocusedContainerColor = Color(0xFF0B1424),
                        cursorColor = JarvisNeonCyan
                    )
                )

                Spacer(modifier = Modifier.height(6.dp))

                // Quick Bookmarks Horizontal Chips
                Row(
                    modifier = Modifier
                        .fillMaxWidth()
                        .horizontalScroll(rememberScrollState()),
                    horizontalArrangement = Arrangement.spacedBy(6.dp)
                ) {
                    quickBookmarks.forEach { (name, url) ->
                        Box(
                            modifier = Modifier
                                .clip(RoundedCornerShape(999.dp))
                                .background(Color(0xFF141F36))
                                .border(1.dp, Color.White.copy(alpha = 0.15f), RoundedCornerShape(999.dp))
                                .clickable {
                                    inputUrl = url
                                    navigateToUrl(url)
                                }
                                .padding(horizontal = 10.dp, vertical = 4.dp)
                        ) {
                            Text(
                                text = name,
                                fontSize = 10.sp,
                                color = JarvisTextPrimary,
                                fontWeight = FontWeight.SemiBold
                            )
                        }
                    }
                }
            }

            // Loading Progress Bar
            if (isLoading) {
                LinearProgressIndicator(
                    modifier = Modifier.fillMaxWidth(),
                    color = JarvisNeonCyan,
                    trackColor = Color(0xFF0F1A2E)
                )
            }

            // 2. MAIN WEBVIEW EMBED
            AndroidView(
                modifier = Modifier
                    .weight(1f)
                    .fillMaxWidth()
                    .testTag("jarvis_browser_webview"),
                factory = { ctx ->
                    WebView(ctx).apply {
                        setLayerType(View.LAYER_TYPE_SOFTWARE, null)
                        settings.apply {
                            javaScriptEnabled = true
                            domStorageEnabled = true
                            loadWithOverviewMode = true
                            useWideViewPort = true
                            builtInZoomControls = true
                            displayZoomControls = false
                        }

                        webViewClient = object : WebViewClient() {
                            override fun onPageStarted(view: WebView?, url: String?, favicon: Bitmap?) {
                                super.onPageStarted(view, url, favicon)
                                isLoading = true
                                url?.let {
                                    currentUrl = it
                                    inputUrl = it
                                }
                                canGoBack = view?.canGoBack() ?: false
                                canGoForward = view?.canGoForward() ?: false
                            }

                            override fun onPageFinished(view: WebView?, url: String?) {
                                super.onPageFinished(view, url)
                                isLoading = false
                                url?.let {
                                    currentUrl = it
                                    inputUrl = it
                                }
                                view?.title?.let { currentTitle = it }
                                canGoBack = view?.canGoBack() ?: false
                                canGoForward = view?.canGoForward() ?: false
                            }

                            override fun onRenderProcessGone(view: WebView?, detail: RenderProcessGoneDetail?): Boolean {
                                android.util.Log.w("JarvisBrowser", "Chromium renderer process termination caught (code -1). Safe recovery engaged.")
                                view?.let {
                                    (it.parent as? ViewGroup)?.removeView(it)
                                    it.destroy()
                                }
                                webViewRef = null
                                isLoading = false
                                return true
                            }
                        }
                        loadUrl(initialUrl)
                        webViewRef = this
                    }
                }
            )

            // 3. BOTTOM AI FLOATING BAR
            Row(
                modifier = Modifier
                    .fillMaxWidth()
                    .background(Color(0xFF0B1424))
                    .border(1.dp, Color.White.copy(alpha = 0.10f), RoundedCornerShape(topStart = 16.dp, topEnd = 16.dp))
                    .padding(horizontal = 12.dp, vertical = 8.dp),
                verticalAlignment = Alignment.CenterVertically,
                horizontalArrangement = Arrangement.SpaceBetween
            ) {
                // AI Summarize Button
                Box(
                    modifier = Modifier
                        .weight(1f)
                        .clip(RoundedCornerShape(14.dp))
                        .background(
                            Brush.horizontalGradient(
                                listOf(JarvisViolet, JarvisVioletBright)
                            )
                        )
                        .clickable {
                            webViewRef?.evaluateJavascript(
                                "(function() { return document.body.innerText; })();"
                            ) { extractedText ->
                                val clean = extractedText?.trim('"')?.replace("\\n", " ")?.take(1500) ?: ""
                                if (clean.isNotBlank()) {
                                    isSummarizing = true
                                    isSummaryModalOpen = true
                                    coroutineScope.launch {
                                        summaryResult = onSummarizeContent(clean)
                                        isSummarizing = false
                                    }
                                }
                            }
                        }
                        .padding(vertical = 10.dp)
                        .testTag("browser_ai_summarize_btn"),
                    contentAlignment = Alignment.Center
                ) {
                    Row(
                        verticalAlignment = Alignment.CenterVertically,
                        horizontalArrangement = Arrangement.spacedBy(6.dp)
                    ) {
                        Icon(
                            imageVector = Icons.Default.AutoAwesome,
                            contentDescription = null,
                            tint = Color.White,
                            modifier = Modifier.size(16.dp)
                        )
                        Text(
                            text = "AI Page Summary",
                            fontSize = 11.sp,
                            fontWeight = FontWeight.Bold,
                            color = Color.White
                        )
                    }
                }

                Spacer(modifier = Modifier.width(10.dp))

                // Read Aloud TTS Button
                Box(
                    modifier = Modifier
                        .weight(1f)
                        .clip(RoundedCornerShape(14.dp))
                        .background(
                            Brush.horizontalGradient(
                                listOf(JarvisNeonCyan, Color(0xFF00B0FF))
                            )
                        )
                        .clickable {
                            webViewRef?.evaluateJavascript(
                                "(function() { return document.body.innerText; })();"
                            ) { extractedText ->
                                val clean = extractedText?.trim('"')?.replace("\\n", " ")?.take(400) ?: ""
                                if (clean.isNotBlank()) {
                                    JarvisTtsManager.speak(context, "Page content: $clean")
                                }
                            }
                        }
                        .padding(vertical = 10.dp)
                        .testTag("browser_read_aloud_btn"),
                    contentAlignment = Alignment.Center
                ) {
                    Row(
                        verticalAlignment = Alignment.CenterVertically,
                        horizontalArrangement = Arrangement.spacedBy(6.dp)
                    ) {
                        Icon(
                            imageVector = Icons.Default.VolumeUp,
                            contentDescription = null,
                            tint = Color(0xFF05131E),
                            modifier = Modifier.size(16.dp)
                        )
                        Text(
                            text = "Listen / Read Aloud",
                            fontSize = 11.sp,
                            fontWeight = FontWeight.Bold,
                            color = Color(0xFF05131E)
                        )
                    }
                }
            }
        }

        // 4. FLOATING AI SUMMARY BOTTOM SHEET
        AnimatedVisibility(
            visible = isSummaryModalOpen,
            enter = slideInVertically(initialOffsetY = { it }) + fadeIn(),
            exit = slideOutVertically(targetOffsetY = { it }) + fadeOut(),
            modifier = Modifier.align(Alignment.BottomCenter)
        ) {
            JarvisGlassPanel(
                accentColor = JarvisVioletBright,
                cornerRadius = 24.dp,
                modifier = Modifier
                    .fillMaxWidth()
                    .padding(12.dp)
            ) {
                Column(
                    modifier = Modifier
                        .fillMaxWidth()
                        .padding(14.dp),
                    verticalArrangement = Arrangement.spacedBy(10.dp)
                ) {
                    Row(
                        modifier = Modifier.fillMaxWidth(),
                        horizontalArrangement = Arrangement.SpaceBetween,
                        verticalAlignment = Alignment.CenterVertically
                    ) {
                        Row(
                            verticalAlignment = Alignment.CenterVertically,
                            horizontalArrangement = Arrangement.spacedBy(6.dp)
                        ) {
                            Icon(
                                imageVector = Icons.Default.AutoAwesome,
                                contentDescription = null,
                                tint = JarvisVioletBright,
                                modifier = Modifier.size(18.dp)
                            )
                            Text(
                                text = "Neural Page Intelligence",
                                style = MaterialTheme.typography.titleSmall,
                                color = Color.White,
                                fontWeight = FontWeight.ExtraBold
                            )
                        }

                        IconButton(
                            onClick = { isSummaryModalOpen = false },
                            modifier = Modifier.size(28.dp)
                        ) {
                            Icon(
                                imageVector = Icons.Default.Close,
                                contentDescription = "Close",
                                tint = Color.White.copy(alpha = 0.7f),
                                modifier = Modifier.size(18.dp)
                            )
                        }
                    }

                    if (isSummarizing) {
                        Row(
                            modifier = Modifier
                                .fillMaxWidth()
                                .padding(vertical = 20.dp),
                            horizontalArrangement = Arrangement.Center,
                            verticalAlignment = Alignment.CenterVertically
                        ) {
                            CircularProgressIndicator(
                                color = JarvisVioletBright,
                                modifier = Modifier.size(24.dp),
                                strokeWidth = 2.dp
                            )
                            Spacer(modifier = Modifier.width(10.dp))
                            Text(
                                text = "JARVIS analyzing DOM content...",
                                color = JarvisTextSecondary,
                                fontSize = 12.sp
                            )
                        }
                    } else {
                        val summary = summaryResult ?: "No summary available."
                        Box(
                            modifier = Modifier
                                .fillMaxWidth()
                                .height(160.dp)
                                .clip(RoundedCornerShape(12.dp))
                                .background(Color(0xFF0F172A))
                                .padding(10.dp)
                                .verticalScroll(rememberScrollState())
                        ) {
                            Text(
                                text = summary,
                                style = MaterialTheme.typography.bodySmall,
                                color = Color.White.copy(alpha = 0.9f),
                                lineHeight = 18.sp
                            )
                        }

                        Row(
                            modifier = Modifier.fillMaxWidth(),
                            horizontalArrangement = Arrangement.End,
                            verticalAlignment = Alignment.CenterVertically
                        ) {
                            IconButton(
                                onClick = {
                                    clipboardManager.setText(AnnotatedString(summary))
                                }
                            ) {
                                Icon(
                                    imageVector = Icons.Default.ContentCopy,
                                    contentDescription = "Copy",
                                    tint = JarvisNeonCyan,
                                    modifier = Modifier.size(18.dp)
                                )
                            }

                            Spacer(modifier = Modifier.width(8.dp))

                            Box(
                                modifier = Modifier
                                    .clip(RoundedCornerShape(999.dp))
                                    .background(JarvisVioletBright)
                                    .clickable {
                                        JarvisTtsManager.speak(context, summary)
                                    }
                                    .padding(horizontal = 14.dp, vertical = 6.dp)
                            ) {
                                Row(
                                    verticalAlignment = Alignment.CenterVertically,
                                    horizontalArrangement = Arrangement.spacedBy(4.dp)
                                ) {
                                    Icon(
                                        imageVector = Icons.Default.VolumeUp,
                                        contentDescription = null,
                                        tint = Color.White,
                                        modifier = Modifier.size(14.dp)
                                    )
                                    Text(
                                        text = "Speak Summary",
                                        fontSize = 11.sp,
                                        fontWeight = FontWeight.Bold,
                                        color = Color.White
                                    )
                                }
                            }
                        }
                    }
                }
            }
        }
    }
}
