@Composable
fun BrowserScreen(
    initialUrl: String = "https://www.google.com",
    onBack: () -> Unit,
    onSummarizeContent: suspend (String) -> String = { "Page summary generated by JARVIS Neural Core." }
) {
    val context = LocalContext.current
    val coroutineScope = rememberCoroutineScope()
    val clipboardManager = LocalClipboardManager.current

    var currentUrl by remember { mutableStateOf(NativeWebReaderEngine.normalizeUrl(initialUrl)) }
    var inputUrl by remember { mutableStateOf(currentUrl) }
    var currentTitle by remember { mutableStateOf("JARVIS Safari Web Studio") }
    var isLoading by remember { mutableStateOf(false) }
    var reloadNonce by remember { mutableIntStateOf(0) }
    var snapshot by remember { mutableStateOf<NativeWebPageSnapshot?>(null) }
    val historyStack = remember { mutableStateListOf<String>() }

    // AI Summary Dialog State
    var isSummarizing by remember { mutableStateOf(false) }
    var summaryResult by remember { mutableStateOf<String?>(null) }
    var isSummaryModalOpen by remember { mutableStateOf(false) }

    val quickBookmarks = listOf(
        "Google" to "https://www.google.com",
        "Wikipedia" to "https://en.wikipedia.org",
        "GitHub" to "https://github.com",
        "Gemini" to "https://gemini.google.com",
        "HackerNews" to "https://news.ycombinator.com",
        "TechCrunch" to "https://techcrunch.com"
    )

    fun navigateToUrl(target: String, pushHistory: Boolean = true) {
        val finalUrl = NativeWebReaderEngine.normalizeUrl(target)
        if (pushHistory && finalUrl != currentUrl) {
            historyStack.add(currentUrl)
        }
        currentUrl = finalUrl
        inputUrl = finalUrl
    }

    LaunchedEffect(currentUrl, reloadNonce) {
        isLoading = true
        val fetched = NativeWebReaderEngine.fetchAndParseUrl(currentUrl)
        snapshot = fetched
        currentTitle = fetched.title
        inputUrl = fetched.url
        isLoading = false
    }

    BackHandler {
        if (historyStack.isNotEmpty()) {
            val prev = historyStack.removeAt(historyStack.lastIndex)
            currentUrl = prev
            inputUrl = prev
        } else {
            onBack()
        }
    }

    Box(
        modifier = Modifier
            .fillMaxSize()
            .background(Color.Transparent)
    ) {
        Column(modifier = Modifier.fillMaxSize()) {
            // 1. APPLE iOS 26 SAFARI MULTI-COLOR LIQUID GLASS HEADER & URL BAR
            Column(
                modifier = Modifier
                    .fillMaxWidth()
                    .padding(horizontal = 12.dp, vertical = 8.dp)
                    .clip(RoundedCornerShape(24.dp))
                    .background(
                        Brush.verticalGradient(
                            colors = listOf(
                                Color(0xEE141A33),
                                Color(0xE60D1224)
                            )
                        )
                    )
                    .border(
                        width = 1.dp,
                        brush = Brush.horizontalGradient(
                            listOf(
                                RoyalPurplePrimary.copy(alpha = 0.70f),
                                AccentSkyCyan.copy(alpha = 0.60f),
                                AccentRosePink.copy(alpha = 0.60f)
                            )
                        ),
                        shape = RoundedCornerShape(24.dp)
                    )
                    .padding(horizontal = 12.dp, vertical = 10.dp)
            ) {
                // Top Action Row
                Row(
                    modifier = Modifier.fillMaxWidth(),
                    verticalAlignment = Alignment.CenterVertically,
                    horizontalArrangement = Arrangement.SpaceBetween
                ) {
                    Row(
                        verticalAlignment = Alignment.CenterVertically,
                        horizontalArrangement = Arrangement.spacedBy(4.dp)
                    ) {
                        IconButton(
                            onClick = {
                                if (historyStack.isNotEmpty()) {
                                    val prev = historyStack.removeAt(historyStack.lastIndex)
                                    currentUrl = prev
                                    inputUrl = prev
                                } else {
                                    onBack()
                                }
                            },
                            modifier = Modifier.testTag("browser_back_btn")
                        ) {
                            Icon(
                                imageVector = Icons.AutoMirrored.Filled.ArrowBack,
                                contentDescription = "Back",
                                tint = AccentSkyCyan
                            )
                        }

                        IconButton(
                            onClick = {
                                navigateToUrl("https://www.google.com")
                            },
                            modifier = Modifier.testTag("browser_home_btn")
                        ) {
                            Icon(
                                imageVector = Icons.Default.Home,
                                contentDescription = "Home",
                                tint = RoyalPurplePrimary
                            )
                        }

                        IconButton(
                            onClick = { reloadNonce++ },
                            modifier = Modifier.testTag("browser_refresh_btn")
                        ) {
                            Icon(
                                imageVector = Icons.Default.Refresh,
                                contentDescription = "Reload",
                                tint = AccentMintEmerald
                            )
                        }
                    }

                    // Page Title Pill
                    Box(
                        modifier = Modifier
                            .weight(1f)
                            .padding(horizontal = 6.dp)
                            .clip(RoundedCornerShape(999.dp))
                            .background(Color(0xFF131D33))
                            .border(1.dp, AccentSkyCyan.copy(alpha = 0.35f), RoundedCornerShape(999.dp))
                            .padding(horizontal = 12.dp, vertical = 5.dp),
                        contentAlignment = Alignment.Center
                    ) {
                        Text(
                            text = currentTitle,
                            style = MaterialTheme.typography.labelSmall,
                            color = TextPureWhite,
                            fontWeight = FontWeight.ExtraBold,
                            maxLines = 1,
                            overflow = TextOverflow.Ellipsis
                        )
                    }

                    // External Browser Button
                    IconButton(
                        onClick = {
                            try {
                                val browserIntent = Intent(Intent.ACTION_VIEW, Uri.parse(currentUrl))
                                context.startActivity(browserIntent)
                            } catch (_: Exception) {
                            }
                        },
                        modifier = Modifier.testTag("browser_open_external_btn")
                    ) {
                        Icon(
                            imageVector = Icons.AutoMirrored.Filled.OpenInNew,
                            contentDescription = "Open in Chrome",
                            tint = AccentChampagneGold
                        )
                    }
                }

                Spacer(modifier = Modifier.height(6.dp))

                // Editable URL / Search Field
                OutlinedTextField(
                    value = inputUrl,
                    onValueChange = { inputUrl = it },
                    modifier = Modifier
                        .fillMaxWidth()
                        .height(52.dp)
                        .testTag("browser_url_input"),
                    placeholder = {
                        Text(
                            text = "Search Google or type web URL...",
                            fontSize = 12.sp,
                            color = TextLavenderMuted
                        )
                    },
                    leadingIcon = {
                        Icon(
                            imageVector = Icons.Default.Search,
                            contentDescription = null,
                            tint = AccentSkyCyan,
                            modifier = Modifier.size(18.dp)
                        )
                    },
                    trailingIcon = {
                        Row(verticalAlignment = Alignment.CenterVertically) {
                            if (inputUrl.isNotBlank()) {
                                IconButton(
                                    onClick = { inputUrl = "" },
                                    modifier = Modifier.size(32.dp)
                                ) {
                                    Icon(
                                        imageVector = Icons.Default.Clear,
                                        contentDescription = "Clear",
                                        tint = TextLavenderMuted,
                                        modifier = Modifier.size(16.dp)
                                    )
                                }
                            }
                            Box(
                                modifier = Modifier
                                    .padding(end = 4.dp)
                                    .clip(RoundedCornerShape(12.dp))
                                    .background(
                                        Brush.horizontalGradient(
                                            listOf(RoyalPurplePrimary, AccentSkyCyan)
                                        )
                                    )
                                    .clickable { navigateToUrl(inputUrl) }
                                    .padding(horizontal = 12.dp, vertical = 6.dp)
                                    .testTag("browser_go_btn")
                            ) {
                                Text(
                                    text = "GO",
                                    fontSize = 11.sp,
                                    fontWeight = FontWeight.ExtraBold,
                                    color = Color.White
                                )
                            }
                        }
                    },
                    singleLine = true,
                    textStyle = MaterialTheme.typography.bodySmall.copy(
                        color = Color.White,
                        fontFamily = FontFamily.Monospace,
                        fontSize = 12.sp
                    ),
                    keyboardOptions = KeyboardOptions(imeAction = ImeAction.Go),
                    keyboardActions = KeyboardActions(onGo = { navigateToUrl(inputUrl) }),
                    shape = RoundedCornerShape(16.dp),
                    colors = OutlinedTextFieldDefaults.colors(
                        focusedBorderColor = AccentSkyCyan,
                        unfocusedBorderColor = Color.White.copy(alpha = 0.20f),
                        focusedContainerColor = Color(0xFF0B1424),
                        unfocusedContainerColor = Color(0xFF0B1424),
                        cursorColor = AccentSkyCyan
                    )
                )

                Spacer(modifier = Modifier.height(8.dp))

                // Quick Bookmarks Horizontal Multi-Color Chips
                val chipAccents = listOf(
                    AccentSkyCyan,
                    RoyalPurplePrimary,
                    AccentMintEmerald,
                    AccentRosePink,
                    AccentChampagneGold,
                    RoyalIndigoAccent
                )
                Row(
                    modifier = Modifier
                        .fillMaxWidth()
                        .horizontalScroll(rememberScrollState()),
                    horizontalArrangement = Arrangement.spacedBy(6.dp)
                ) {
                    quickBookmarks.forEachIndexed { idx, (name, url) ->
                        val accent = chipAccents[idx % chipAccents.size]
                        Box(
                            modifier = Modifier
                                .clip(RoundedCornerShape(999.dp))
                                .background(accent.copy(alpha = 0.18f))
                                .border(1.dp, accent.copy(alpha = 0.55f), RoundedCornerShape(999.dp))
                                .clickable {
                                    inputUrl = url
                                    navigateToUrl(url)
                                }
                                .padding(horizontal = 12.dp, vertical = 5.dp)
                        ) {
                            Text(
                                text = name,
                                fontSize = 11.sp,
                                color = Color.White,
                                fontWeight = FontWeight.ExtraBold
                            )
                        }
                    }
                }
            }

            // Loading Progress Bar
            if (isLoading) {
                LinearProgressIndicator(
                    modifier = Modifier.fillMaxWidth(),
                    color = AccentSkyCyan,
                    trackColor = Color(0xFF0F1A2E)
                )
            }

            // 2. NATIVE CRASH-FREE SAFARI READER & DOM ENGINE VIEW
            NativeWebSnapshotContent(
                snapshot = snapshot,
                onNavigateLink = { linkUrl -> navigateToUrl(linkUrl) },
                onOpenExternal = { extUrl ->
                    try {
                        context.startActivity(Intent(Intent.ACTION_VIEW, Uri.parse(extUrl)))
                    } catch (_: Exception) {
                    }
                },
                modifier = Modifier
                    .weight(1f)
                    .fillMaxWidth()
                    .testTag("jarvis_browser_webview")
            )

            // 3. BOTTOM AI FLOATING ACTION DOCK
            Row(
                modifier = Modifier
                    .fillMaxWidth()
                    .padding(horizontal = 12.dp, vertical = 8.dp)
                    .clip(RoundedCornerShape(20.dp))
                    .background(Color(0xEE11162B))
                    .border(1.dp, Color.White.copy(alpha = 0.14f), RoundedCornerShape(20.dp))
                    .padding(horizontal = 12.dp, vertical = 10.dp),
                verticalAlignment = Alignment.CenterVertically,
                horizontalArrangement = Arrangement.SpaceBetween
            ) {
                // AI Summarize Button
                Box(
                    modifier = Modifier
                        .weight(1f)
                        .clip(RoundedCornerShape(14.dp))
                        .background(
                            Brush.horizontalGradient(
                                listOf(RoyalPurplePrimary, AccentRosePink)
                            )
                        )
                        .clickable {
                            val clean = snapshot?.rawPlainText?.take(1500).orEmpty()
                            if (clean.isNotBlank()) {
                                isSummarizing = true
                                isSummaryModalOpen = true
                                coroutineScope.launch {
                                    summaryResult = onSummarizeContent(clean)
                                    isSummarizing = false
                                }
                            }
                        }
                        .padding(vertical = 11.dp)
                        .testTag("browser_ai_summarize_btn"),
                    contentAlignment = Alignment.Center
                ) {
                    Row(
                        verticalAlignment = Alignment.CenterVertically,
                        horizontalArrangement = Arrangement.spacedBy(6.dp)
                    ) {
                        Icon(
                            imageVector = Icons.Default.AutoAwesome,
                            contentDescription = null,
                            tint = Color.White,
                            modifier = Modifier.size(16.dp)
                        )
                        Text(
                            text = "AI Page Summary",
                            fontSize = 12.sp,
                            fontWeight = FontWeight.ExtraBold,
                            color = Color.White
                        )
                    }
                }

                Spacer(modifier = Modifier.width(10.dp))

                // Read Aloud TTS Button
                Box(
                    modifier = Modifier
                        .weight(1f)
                        .clip(RoundedCornerShape(14.dp))
                        .background(
                            Brush.horizontalGradient(
                                listOf(AccentSkyCyan, AccentMintEmerald)
                            )
                        )
                        .clickable {
                            val clean = snapshot?.rawPlainText?.take(420).orEmpty()
                            if (clean.isNotBlank()) {
                                JarvisTtsManager.speak(context, "Page content: $clean")
                            }
                        }
                        .padding(vertical = 11.dp)
                        .testTag("browser_read_aloud_btn"),
                    contentAlignment = Alignment.Center
                ) {
                    Row(
                        verticalAlignment = Alignment.CenterVertically,
                        horizontalArrangement = Arrangement.spacedBy(6.dp)
                    ) {
                        Icon(
                            imageVector = Icons.AutoMirrored.Filled.VolumeUp,
                            contentDescription = null,
                            tint = Color.White,
                            modifier = Modifier.size(16.dp)
                        )
                        Text(
                            text = "Listen / Read Aloud",
                            fontSize = 12.sp,
                            fontWeight = FontWeight.ExtraBold,
                            color = Color.White
                        )
                    }
                }
            }
        }

        // 4. FLOATING AI SUMMARY BOTTOM SHEET
        AnimatedVisibility(
            visible = isSummaryModalOpen,
            enter = slideInVertically(initialOffsetY = { it }) + fadeIn(),
            exit = slideOutVertically(targetOffsetY = { it }) + fadeOut(),
            modifier = Modifier.align(Alignment.BottomCenter)
        ) {
            JarvisGlassPanel(
                accentColor = RoyalPurplePrimary,
                cornerRadius = 24.dp,
                modifier = Modifier
                    .fillMaxWidth()
                    .padding(12.dp)
            ) {
                Column(
                    modifier = Modifier
                        .fillMaxWidth()
                        .padding(14.dp),
                    verticalArrangement = Arrangement.spacedBy(10.dp)
                ) {
                    Row(
                        modifier = Modifier.fillMaxWidth(),
                        horizontalArrangement = Arrangement.SpaceBetween,
                        verticalAlignment = Alignment.CenterVertically
                    ) {
                        Row(
                            verticalAlignment = Alignment.CenterVertically,
                            horizontalArrangement = Arrangement.spacedBy(6.dp)
                        ) {
                            Icon(
                                imageVector = Icons.Default.AutoAwesome,
                                contentDescription = null,
                                tint = AccentSkyCyan,
                                modifier = Modifier.size(18.dp)
                            )
                            Text(
                                text = "Neural Page Intelligence",
                                style = MaterialTheme.typography.titleSmall,
                                color = Color.White,
                                fontWeight = FontWeight.ExtraBold
                            )
                        }

                        IconButton(
                            onClick = { isSummaryModalOpen = false },
                            modifier = Modifier.size(28.dp)
                        ) {
                            Icon(
                                imageVector = Icons.Default.Close,
                                contentDescription = "Close",
                                tint = Color.White.copy(alpha = 0.7f),
                                modifier = Modifier.size(18.dp)
                            )
                        }
                    }

                    if (isSummarizing) {
                        Row(
                            modifier = Modifier
                                .fillMaxWidth()
                                .padding(vertical = 20.dp),
                            horizontalArrangement = Arrangement.Center,
                            verticalAlignment = Alignment.CenterVertically
                        ) {
                            CircularProgressIndicator(
                                color = AccentSkyCyan,
                                modifier = Modifier.size(24.dp),
                                strokeWidth = 2.dp
                            )
                            Spacer(modifier = Modifier.width(10.dp))
                            Text(
                                text = "Analyzing page content...",
                                color = TextLavenderMuted,
                                fontSize = 12.sp
                            )
                        }
                    } else {
                        val summary = summaryResult ?: "No summary available."
                        Box(
                            modifier = Modifier
                                .fillMaxWidth()
                                .height(160.dp)
                                .clip(RoundedCornerShape(12.dp))
                                .background(Color(0xFF0F172A))
                                .padding(10.dp)
                                .verticalScroll(rememberScrollState())
                        ) {
                            Text(
                                text = summary,
                                style = MaterialTheme.typography.bodySmall,
                                color = Color.White.copy(alpha = 0.9f),
                                lineHeight = 18.sp
                            )
                        }

                        Row(
                            modifier = Modifier.fillMaxWidth(),
                            horizontalArrangement = Arrangement.End,
                            verticalAlignment = Alignment.CenterVertically
                        ) {
                            IconButton(
                                onClick = {
                                    clipboardManager.setText(AnnotatedString(summary))
                                }
                            ) {
                                Icon(
                                    imageVector = Icons.Default.ContentCopy,
                                    contentDescription = "Copy",
                                    tint = AccentSkyCyan,
                                    modifier = Modifier.size(18.dp)
                                )
                            }

                            Spacer(modifier = Modifier.width(8.dp))

                            Box(
                                modifier = Modifier
                                    .clip(RoundedCornerShape(999.dp))
                                    .background(
                                        Brush.horizontalGradient(
                                            listOf(RoyalPurplePrimary, AccentRosePink)
                                        )
                                    )
                                    .clickable {
                                        JarvisTtsManager.speak(context, summary)
                                    }
                                    .padding(horizontal = 14.dp, vertical = 6.dp)
                            ) {
                                Row(
                                    verticalAlignment = Alignment.CenterVertically,
                                    horizontalArrangement = Arrangement.spacedBy(4.dp)
                                ) {
                                    Icon(
                                        imageVector = Icons.AutoMirrored.Filled.VolumeUp,
                                        contentDescription = null,
                                        tint = Color.White,
                                        modifier = Modifier.size(14.dp)
                                    )
                                    Text(
                                        text = "Speak Summary",
                                        fontSize = 11.sp,
                                        fontWeight = FontWeight.Bold,
                                        color = Color.White
                                    )
                                }
                            }
                        }
                    }
                }
            }
        }
    }
}
